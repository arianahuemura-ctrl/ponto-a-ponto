import {test,expect} from './coverage.js';
for(const width of [390,1200])test(`alterar embarque exibe pontos e preserva destino em ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:850});
 const stops=[{id:'1',name:'Embarque inicial',lat:-23.56,lon:-46.68},{id:'2',name:'Novo embarque',lat:-23.5605,lon:-46.679},{id:'3',name:'Destino',lat:-23.561,lon:-46.681}];
 await page.route('https://tile.openstreetmap.org/**',r=>r.abort());
 await page.route('**/api/location-config/**',r=>r.fulfill({json:{position:null}}));
 await page.route('**/api/sptrans/stops/**',r=>r.fulfill({json:{stops:new URL(r.request().url()).searchParams.has('id')?[stops[0]]:stops}}));
 await page.route('**/api/sptrans/board/**',r=>r.fulfill({json:{lines:[],journeys:[]}}));
 await page.goto('/?stop=1');
 await page.getByRole('button',{name:'Selecionar destino',exact:true}).click();
 await page.locator('.sp-stop[title^="Destino · 3"]').click();
 await expect(page.getByRole('dialog',{name:'Ônibus da sua rota'})).toBeVisible();
 await page.getByRole('button',{name:'Ver mapa',exact:true}).click();
 await expect(page.locator('.sp-stop')).toHaveCount(2);
 await expect(page.getByRole('button',{name:'Alterar embarque',exact:true})).toContainText('Definido');
 await expect(page.getByRole('button',{name:'Alterar destino',exact:true})).toContainText('Definido');
 await page.locator('.leaflet-control-zoom-in').click();
 await page.waitForTimeout(400);
 const box=await page.locator('.sp-map').boundingBox();
 await page.mouse.move(box.x+box.width*.6,box.y+box.height*.4);
 await page.mouse.down();await page.mouse.move(box.x+box.width*.6+45,box.y+box.height*.4+35,{steps:8});await page.mouse.up();
 await page.waitForTimeout(400);
 const markerPosition=()=>page.locator('.sp-origin').evaluate(el=>{
  const marker=el.getBoundingClientRect(),map=document.querySelector('.sp-map').getBoundingClientRect();
  return {x:marker.x-map.x-map.width/2,y:marker.y-map.y-map.height/2};
 });
 const beforeOrigin=await markerPosition();
 await page.getByRole('button',{name:'Alterar embarque',exact:true}).click();
 await expect.poll(markerPosition).toEqual(beforeOrigin);
 await expect(page.getByRole('button',{name:'Alterar embarque',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.getByRole('button',{name:'Alterar embarque',exact:true})).toContainText('Selecionando');
 await expect(page.locator('.sp-stop')).toHaveCount(3);
 const transparency=page.getByRole('button',{name:'Pontos transparentes',exact:true});
 const newStop=page.locator('.sp-stop[title^="Novo embarque · 2"]');
 await transparency.click();
 await expect(transparency).toHaveAttribute('aria-pressed','true');
 await expect(newStop).toHaveCSS('opacity','0.25');
 await expect(page.locator('.sp-origin')).toHaveCSS('opacity','1');
 await expect.poll(markerPosition).toEqual(beforeOrigin);
 await transparency.click();
 await expect(newStop).toHaveCSS('opacity','1');
 await transparency.click();
 await expect(newStop).toHaveCSS('opacity','0.25');
 await newStop.click();
 await expect(transparency).toHaveCount(0);
 await expect(page.getByRole('dialog',{name:'Ônibus da sua rota'})).toContainText('Novo embarque');
 const session=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('pap.sp.session')));
 expect(session.origin.id).toBe('2');expect(session.destination.id).toBe('3');
 await page.getByRole('button',{name:'Ver mapa',exact:true}).click();
 await page.locator('.leaflet-control-zoom-in').click();await page.waitForTimeout(400);
 const beforeDestination=await markerPosition();
 await page.getByRole('button',{name:'Horários de embarque',exact:true}).click();
 await page.getByRole('button',{name:'Alterar destino',exact:true}).click();
 await expect.poll(markerPosition).toEqual(beforeDestination);
 await expect(page.locator('.sp-stop')).toHaveCount(3);
});
