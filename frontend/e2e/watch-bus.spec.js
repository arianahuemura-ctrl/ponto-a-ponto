import {test,expect} from './coverage.js';
for(const width of [390,1200])test(`ônibus pode ser acompanhado sem destino em ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:850});
 const now='2026-10-08T02:01:00-03:00';
 await page.clock.install({time:new Date(now)});
 const stop={id:'1',name:'Brasil C/B',lat:-23.56,lon:-46.68};
 await page.route('https://tile.openstreetmap.org/**',r=>r.abort());
 await page.route('**/api/location-config/**',r=>r.fulfill({json:{position:null}}));
 await page.route('**/api/sptrans/stops/**',r=>r.fulfill({json:{stops:[stop,{id:'2',name:'Outra parada',lat:-23.562,lon:-46.682}]}}));
 await page.route('**/api/sptrans/board/**',r=>r.fulfill({json:{lines:[{trip_id:'T',code:'778R-10',headsign:'Centro',arrivals:[{time:'02:10',observed_at:now,vehicle:'81614',accessible:true}]}],journeys:[]}}));
 let requests=0;
 await page.route('**/api/sptrans/trips/T/**',r=>{
  requests++;expect(new URL(r.request().url()).searchParams.get('vehicle')).toBe('81614');
  return r.fulfill({json:{line:{arrivals:[]},approach:requests>1?null:{label:'Próximo ônibus',vehicle:{id:'81614',code:'778R-10',lat:-23.561,lon:-46.685,observed_at:now},geometry:[[-23.561,-46.685],[-23.56,-46.68]]}}});
 });
 await page.goto('/?stop=1');
 await page.getByRole('button',{name:'Ver veículo 81614 da linha 778R-10 no mapa'}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.locator('.sp-live-bus')).toBeVisible();
 await expect(page.locator('.sp-stop:not(.sp-origin)')).toHaveCount(0);
 await expect(page.locator('.sp-watch-panel')).toContainText('Percurso até Brasil C/B');
 expect(await page.evaluate(()=>JSON.parse(sessionStorage.getItem('pap.sp.session')).destination)).toBeNull();
 await page.clock.fastForward(5000);
 await expect.poll(()=>requests).toBeGreaterThan(1);
 await expect(page.locator('.sp-watch-panel')).toContainText('indisponível');
 await expect(page.locator('.sp-live-bus')).toHaveCount(0);
 await page.getByRole('button',{name:'Voltar aos próximos ônibus'}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Ver mapa',exact:true}).click();
 await page.clock.runFor(500);
 await expect(page.locator('.sp-stop:not(.sp-origin)')).toHaveCount(1);
 await page.getByRole('button',{name:'Horários de embarque',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.getByRole('button',{name:'Ver veículo 81614 da linha 778R-10 no mapa'}).click();
 await expect(page.locator('.sp-stop:not(.sp-origin)')).toHaveCount(0);
 let destinationRequests=0;
 await page.route('**/api/sptrans/destination/**',r=>{
  destinationRequests++;
  return r.fulfill({json:{stop:{id:'2',name:'Destino',lat:-23.562,lon:-46.682},distance_meters:50}});
 });
 const box=await page.locator('.sp-map').boundingBox();
 await page.mouse.move(box.x+box.width*.7,box.y+box.height*.35);
 await page.mouse.down();await page.clock.runFor(700);await page.mouse.up();
 const add=page.getByRole('button',{name:'Adicionar como destino'});
 await expect(add).toBeVisible();expect(destinationRequests).toBe(0);
 await page.clock.runFor(1300);
 await add.click();
 await expect.poll(()=>destinationRequests).toBe(1);
 await expect(page.getByRole('dialog')).toBeVisible();
 const session=await page.evaluate(()=>JSON.parse(sessionStorage.getItem('pap.sp.session')));
 expect(session.origin.id).toBe('1');expect(session.destination.id).toBe('2');
 await expect(page.getByRole('button',{name:'Alterar destino',exact:true})).toBeVisible();
 const favorite=page.getByRole('button',{name:'Adicionar ponto aos favoritos'});
 await expect(favorite).toHaveAttribute('aria-pressed','false');
 await favorite.click();
 await page.getByRole('textbox',{name:'Nome do favorito'}).fill('Casa');
 await page.getByRole('button',{name:'Salvar favorito',exact:true}).click();
 await expect(page.getByRole('button',{name:'Remover favorito',exact:true})).toHaveAttribute('aria-pressed','true');
 const favorites=await page.evaluate(()=>JSON.parse(localStorage.getItem('pap.sp.favorites')));
 expect(favorites).toHaveLength(1);expect(favorites[0].id).toBe('2');
 await page.getByRole('button',{name:'Remover favorito',exact:true}).click();
 await page.getByRole('dialog',{name:'Remover favorito?'}).getByRole('button',{name:'Remover favorito',exact:true}).click();
 await expect(page.getByRole('button',{name:'Adicionar ponto aos favoritos'})).toHaveAttribute('aria-pressed','false');
 await page.getByRole('button',{name:'Alterar destino',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Ônibus da sua rota'})).not.toBeVisible();
});
